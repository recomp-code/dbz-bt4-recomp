# Bakes the FidelityFX FSR2 compute passes (Granite's FSR2 fork, third_party/fsr2) into SPIR-V for the native renderer:
# the one permutation it uses (LDR colour, render-resolution motion vectors, inverted depth, no FP16), plus each pass's
# binding layout from glslang's reflection, so the runtime needs neither a shader compiler nor SPIR-V reflection.
# Output: ps2xRuntime/src/lib/seamvk/fsr2_baked.inc. Run again after updating the fsr2 submodule.
$v = 'C:\DBZBT4Recomp\tools\glslang-build\StandAlone\glslangValidator.exe'
$s = 'C:\DBZBT4Recomp\bt3mod\ps2xRuntime\third_party\parallel-gs\Granite\third_party\fsr2\src\ffx-fsr2-api\shaders'
$out = 'C:\DBZBT4Recomp\bt3mod\ps2xRuntime\src\lib\seamvk\fsr2_baked.inc'
$tmp = Join-Path $env:TEMP 'claude\fsr2bake'; New-Item -ItemType Directory -Force $tmp | Out-Null
# FfxFsr2Pass order: DEPTH_CLIP, RECONSTRUCT_PREVIOUS_DEPTH, LOCK, ACCUMULATE, ACCUMULATE_SHARPEN, RCAS,
# COMPUTE_LUMINANCE_PYRAMID, GENERATE_REACTIVE, TCR_AUTOGENERATE
$passes = @(
    @('ffx_fsr2_depth_clip_pass', 0), @('ffx_fsr2_reconstruct_previous_depth_pass', 0), @('ffx_fsr2_lock_pass', 0),
    @('ffx_fsr2_accumulate_pass', 0), @('ffx_fsr2_accumulate_pass', 1), @('ffx_fsr2_rcas_pass', 0),
    @('ffx_fsr2_compute_luminance_pyramid_pass', 0), @('ffx_fsr2_autogen_reactive_pass', 0), @('ffx_fsr2_tcr_autogen_pass', 0))
$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('// Generated by tools/bake_fsr2.ps1 from Granite third_party/fsr2 (FidelityFX FSR2, MIT). Do not edit.')
$layouts = @()
for ($i = 0; $i -lt $passes.Count; $i++) {
    $name = $passes[$i][0]; $sharp = $passes[$i][1]
    $spv = "$tmp\p$i.spv"
    $refl = & $v -V --target-env vulkan1.1 -S comp -DFFX_GLSL=1 -DFFX_GPU=1 -DFFX_HALF=0 -DFFX_FSR2_OPTION_REPROJECT_USE_LANCZOS_TYPE=0 `
        -DFFX_FSR2_OPTION_HDR_COLOR_INPUT=0 -DFFX_FSR2_OPTION_LOW_RESOLUTION_MOTION_VECTORS=1 -DFFX_FSR2_OPTION_JITTERED_MOTION_VECTORS=0 `
        -DFFX_FSR2_OPTION_INVERTED_DEPTH=1 "-DFFX_FSR2_OPTION_APPLY_SHARPENING=$sharp" -q -I"$s" -o $spv "$s\$name.glsl" 2>&1
    if ($LASTEXITCODE) { throw "$name failed:`n$($refl -join "`n")" }
    $sep = 0; $stor = 0; $ubo = 0; $ssbo = 0; $samp = 0; $section = ''
    foreach ($l in $refl) {
        if ($l -match '^(Uniform reflection|Uniform block reflection|Buffer variable reflection|Buffer block reflection|Pipeline)') { $section = $Matches[1]; continue }
        if ($l -notmatch '^([^:]+): .*type ([0-9a-f]+), .*binding (-?\d+)') { continue }
        $n = $Matches[1]; $t = [Convert]::ToInt32($Matches[2], 16); $b = [int]$Matches[3]
        if ($b -lt 0) { continue }
        switch ($section) {
            'Uniform block reflection' { $ubo = $ubo -bor (1 -shl $b) }
            'Buffer block reflection' { $ssbo = $ssbo -bor (1 -shl $b) }
            'Uniform reflection' {
                if ($n -like 's_*') { $samp = $samp -bor (1 -shl $b) }                          # set 0: the two samplers
                elseif ($t -ge 0x904C -and $t -le 0x906C) { $stor = $stor -bor (1 -shl $b) }     # image2D / uimage2D ...
                else { $sep = $sep -bor (1 -shl $b) } }                                          # texture2D / utexture2D
        }
    }
    $words = [IO.File]::ReadAllBytes($spv); $n32 = $words.Length / 4
    [void]$sb.Append("static const uint32_t kFsr2Pass$i[] = { // $name sharpen=$sharp`n")
    for ($k = 0; $k -lt $n32; $k++) { [void]$sb.Append(('0x{0:x8},' -f [BitConverter]::ToUInt32($words, $k * 4))); if ($k % 12 -eq 11) { [void]$sb.Append("`n") } }
    [void]$sb.AppendLine("`n};")
    $layouts += ('    {{ kFsr2Pass{0}, sizeof(kFsr2Pass{0}), 0x{1:x}u, 0x{2:x}u, 0x{3:x}u, 0x{4:x}u, 0x{5:x}u }},' -f $i, $sep, $stor, $ubo, $ssbo, $samp)
}
[void]$sb.AppendLine('struct Fsr2Baked { const uint32_t *code; size_t size; uint32_t separateImages, storageImages, uniformBuffers, storageBuffers, samplers; };   // set 1 masks; samplers: set 0')
[void]$sb.AppendLine('static const Fsr2Baked kFsr2Baked[] = {')
$layouts | ForEach-Object { [void]$sb.AppendLine($_) }
[void]$sb.AppendLine('};')
[IO.File]::WriteAllText($out, $sb.ToString())
"baked $($passes.Count) passes -> $out ($((Get-Item $out).Length) bytes)"
$layouts
